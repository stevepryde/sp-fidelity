/// `ffxF32ToF16`: the table conversion the SDK documents (denormals kept,
/// infinities and NaNs clamped to ±65504).
pub fn ffx_f32_to_f16(f: FfxFloat32) -> FfxUInt32 {
    let u = f.to_bits();
    let i = (u >> 23) as usize;
    FfxUInt32::from(BASE[i]) + ((u & 0x7f_ffff) >> SHIFT[i])
}

/// `ffxPackHalf2x16`.
pub fn ffx_pack_half_2x16(x: FfxFloat32x2) -> FfxUInt32 {
    ffx_f32_to_f16(x[0]) + (ffx_f32_to_f16(x[1]) << 16)
}
