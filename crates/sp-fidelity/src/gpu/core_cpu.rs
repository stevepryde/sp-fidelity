use crate::types::{FfxFloat32, FfxFloat32x2, FfxUInt8, FfxUInt16, FfxUInt32};

/// `ffxAsUInt32`.
pub fn ffx_as_uint32(x: FfxFloat32) -> FfxUInt32 {
    x.to_bits()
}

/// `ffxMin(FfxFloat32, FfxFloat32)`.
pub fn ffx_min_f32(x: FfxFloat32, y: FfxFloat32) -> FfxFloat32 {
    if x < y { x } else { y }
}

/// `ffxMax(FfxUInt32, FfxUInt32)`.
pub fn ffx_max_u32(x: FfxUInt32, y: FfxUInt32) -> FfxUInt32 {
    if x > y { x } else { y }
}

